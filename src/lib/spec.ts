export interface ScreenSpec {
  /** اسم الشاشة بالعربية كما يعرفه الفريق */
  title: string
  /** لماذا توجد هذه الشاشة — جملة واحدة */
  purpose: string
  /** مصدر البيانات في الموك اب ← وما يقابله في المنتج الحقيقي */
  data: string[]
  /** قواعد لا يجوز كسرها عند البناء */
  rules?: string[]
  /** الحالات التي يجب أن يغطّيها البناء (فارغ · تحميل · خطأ · صلاحيات) */
  states?: string[]
  /** ما هو معروض هنا لكنه **مؤجَّل** — لا يُبنى الآن */
  deferred?: string[]
  /** معايير القبول — متى تُعتبر الشاشة «تمّت» */
  done?: string[]
}

